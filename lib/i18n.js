const DICTS = { uz, ru, en };

export function getLang() {
  const code = cookies().get(LANG_COOKIE)?.value;
  return DICTS[code] ? code : "uz";
}

// Returns t(key, vars) for the current request's language, falling back to Uzbek.
export function getT() {
  const dict = DICTS[getLang()];
  return (key, vars) => {
    let text = dict[key] ?? uz[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

